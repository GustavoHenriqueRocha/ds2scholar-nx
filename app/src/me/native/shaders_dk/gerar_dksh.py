#!/usr/bin/env python3
"""ds2-deko3d: compiles every shader in shaders_dk/ with uam and embeds the DKSH (build step, dkshaders.cmake).

  gerar_dksh.py --uam <uam> --out <dir>          compile all; write <dir>/sa2_native_dk_shaders_data.inc
  gerar_dksh.py --enum <sa2_native_dk_shaders.h>  rewrite the checked-in enum header from the file list
  gerar_dksh.py --check-enum <header>             exit 1 if the header does not match the file list

Every source goes through divisao_exata.trocar first (idempotent: the adapted ones already did; hand-written ones,
like the output pass's output_*, get it here). The build fails when:
  - uam rejects a shader (a float division the rewrite took for an integer one does not compile: there is no
    ds2_udiv(float, float));
  - uam warns about integer division emulation, or its TGSI still has UDIV/UMOD/IDIV/MOD (an integer division the
    rewrite missed);
  - the enum header is out of date (the ids other files use must match the data).
The enum order is the sorted file name list; ids are k + CamelCase of the file stem (me_edram_raw64_to_raw64 ->
kMeEdramRaw64ToRaw64).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

AQUI = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, AQUI)
import divisao_exata  # noqa: E402

ESTAGIOS = {"vert": "vert", "frag": "frag", "comp": "comp"}
TGSI_DIV = re.compile(r"^\s*\d+:\s*(UDIV|UMOD|IDIV|MOD|U64DIV|I64DIV|U64MOD|I64MOD)\b", re.M)
AVISO_DIV = "integer division/modulo"


def fontes():
    return sorted(f for f in os.listdir(AQUI) if f.rsplit(".", 1)[-1] in ESTAGIOS)


def ident(arquivo):
    stem = arquivo.rsplit(".", 1)[0]
    return "k" + "".join(p[:1].upper() + p[1:] for p in stem.split("_"))


def cabecalho(lista):
    linhas = [
        "// ds2-deko3d: ids of the renderer's own DKSH shaders (shaders_dk/, compiled by uam at build time).",
        "// GENERATED by shaders_dk/gerar_dksh.py --enum from the file list; the build checks it is up to date.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace sa2::native::dkshaders {",
        "",
        "enum Id : uint32_t {",
    ]
    linhas += [f"  {ident(f)},  // {f}" for f in lista]
    linhas += [
        "  kCount",
        "};",
        "",
        "// The DKSH of a shader (control + code, as uam wrote it) and its size; for sa2::dk::CodeArena::Load.",
        "const uint8_t* Data(Id id);",
        "size_t Size(Id id);",
        "// The source file name, for logs.",
        "const char* Name(Id id);",
        "",
        "}  // namespace sa2::native::dkshaders",
        "",
    ]
    return "\n".join(linhas)


def compilar(uam, out):
    lista = fontes()
    os.makedirs(out, exist_ok=True)
    blobs, erros = [], []
    with tempfile.TemporaryDirectory(dir=out) as tmp:
        for f in lista:
            with open(os.path.join(AQUI, f)) as h:
                texto, _ = divisao_exata.trocar(h.read())
            src = os.path.join(tmp, f)
            with open(src, "w") as h:
                h.write(texto)
            dksh, tgsi = os.path.join(tmp, f + ".dksh"), os.path.join(tmp, f + ".tgsi")
            r = subprocess.run([uam, "-s", ESTAGIOS[f.rsplit(".", 1)[1]], "-o", dksh, "-t", tgsi, src],
                               capture_output=True, text=True)
            log = r.stdout + r.stderr
            if r.returncode != 0 or not os.path.exists(dksh):
                erros.append(f"{f}: uam failed:\n{log}")
                continue
            if AVISO_DIV in log:
                erros.append(f"{f}: uam still emulates an integer division:\n{log}")
            with open(tgsi) as h:
                if (m := TGSI_DIV.search(h.read())):
                    erros.append(f"{f}: TGSI still has {m.group(1)} (an integer division the rewrite missed)")
            with open(dksh, "rb") as h:
                blobs.append(h.read())
    if erros:
        sys.exit("gerar_dksh.py:\n" + "\n".join(erros))
    linhas = ["// GENERATED by shaders_dk/gerar_dksh.py at build time: the DKSH of each sa2::native::dkshaders::Id.",
              "// clang-format off"]
    for f, b in zip(lista, blobs):
        corpo = ",".join(f"0x{x:02x}" for x in b)
        linhas.append(f"alignas(256) static const uint8_t kData_{ident(f)}[{len(b)}] = {{{corpo}}};")
    linhas.append("static const uint8_t* const kDatas[] = {" + ", ".join(f"kData_{ident(f)}" for f in lista) + "};")
    linhas.append("static const size_t kSizes[] = {" + ", ".join(str(len(b)) for b in blobs) + "};")
    linhas.append("static const char* const kNames[] = {" + ", ".join(f'"{f}"' for f in lista) + "};")
    destino = os.path.join(out, "sa2_native_dk_shaders_data.inc")
    with open(destino + ".tmp", "w") as h:
        h.write("\n".join(linhas) + "\n")
    os.replace(destino + ".tmp", destino)
    print(f"gerar_dksh.py: {len(blobs)} DKSH, {sum(map(len, blobs))} bytes -> {destino}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--uam")
    p.add_argument("--out")
    p.add_argument("--enum")
    p.add_argument("--check-enum")
    a = p.parse_args()
    if a.enum:
        with open(a.enum, "w") as h:
            h.write(cabecalho(fontes()))
        print(f"gerar_dksh.py: {a.enum} ({len(fontes())} ids)")
    if a.check_enum:
        with open(a.check_enum) as h:
            if h.read() != cabecalho(fontes()):
                sys.exit(f"gerar_dksh.py: {a.check_enum} is out of date: run gerar_dksh.py --enum {a.check_enum}")
    if a.uam:
        compilar(a.uam, a.out)


if __name__ == "__main__":
    main()
